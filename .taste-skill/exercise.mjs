import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { Browser, sleep } from '/Users/darius/.agents/skills/design-taste-frontend/scripts/lib/cdp.mjs';
mkdirSync('.taste-skill/states', { recursive: true });
const browser = await Browser.launch();
const results = [];
try {
  for (const width of [1440, 768, 390]) {
    const page = await browser.newPage({ width, height: width === 390 ? 844 : width === 768 ? 1024 : 900 });
    await page.goto('http://127.0.0.1:3000', { settleMs: 300 });
    await page.eval('document.fonts.ready');
    await page.eval(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Add job').click());
    await sleep(120);
    assert.equal(await page.eval(() => document.querySelector('dialog')?.open), true);
    const hover = await page.eval(() => { const r = document.querySelector('.multi-trigger').getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; });
    await page.send('Input.dispatchMouseEvent', { type: 'mouseMoved', ...hover });
    const style = await page.eval(() => { const s = getComputedStyle(document.querySelector('.multi-trigger')); return { background: s.backgroundColor, border: s.boxShadow }; });
    assert.equal(style.background, 'rgb(255, 255, 255)');
    assert.ok(style.border.includes('inset'));
    await page.eval(() => document.querySelector('.multi-trigger').click());
    await sleep(80);
    await page.eval(() => { const checks = document.querySelectorAll('.multi-options input[type="checkbox"]'); checks[0].click(); checks[1].click(); });
    await sleep(80);
    assert.ok(await page.eval(() => document.querySelector('.multi-trigger').textContent.includes('2 selected')));
    await page.eval(() => { const input = document.querySelector('.multi-choices input[type="search"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'H100'); input.dispatchEvent(new Event('input', { bubbles: true })); });
    await sleep(80);
    assert.equal(await page.eval(() => document.querySelectorAll('.multi-options input[type="checkbox"]').length), 1);
    assert.ok(await page.eval(() => document.querySelector('.multi-trigger').textContent.includes('2 selected')));
    await page.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
    await page.send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
    await sleep(80);
    assert.equal(await page.eval(() => document.querySelector('dialog')?.open), true);
    assert.equal(await page.eval(() => document.querySelector('.multi-trigger').getAttribute('aria-expanded')), 'false');
    const name = `Design check ${width}`;
    await page.eval((name) => { const input = document.querySelector('.modal-fields > label input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, name); input.dispatchEvent(new Event('input', { bubbles: true })); }, name);
    await page.screenshot({ path: `.taste-skill/states/${width}-modal.jpg`, fullPage: false });
    await page.eval(() => { const select = document.querySelector('dialog select'); select.value = 'CPU'; select.dispatchEvent(new Event('change', { bubbles: true })); });
    await sleep(80);
    await page.eval(() => document.querySelector('dialog form').requestSubmit());
    await sleep(150);
    assert.equal(await page.eval(() => document.querySelector('dialog')), null);
    assert.ok(await page.eval(name => document.querySelector('.job-details-title').textContent.includes(name), name));
    assert.equal(await page.eval(() => document.querySelectorAll('[role="tabpanel"] tbody tr').length), 7);
    await page.screenshot({ path: `.taste-skill/states/${width}-workloads.jpg`, fullPage: true });
    await page.eval(() => document.getElementById('tab-market').click());
    await sleep(80);
    assert.ok(await page.eval(() => document.querySelector('.chart path[stroke]')?.getAttribute('d').includes('H')));
    await page.screenshot({ path: `.taste-skill/states/${width}-market.jpg`, fullPage: true });
    await page.eval(() => document.getElementById('tab-replay').click());
    await sleep(80);
    assert.ok(await page.eval(() => [...document.querySelectorAll('button')].filter(b => b.disabled).length >= 5));
    await page.screenshot({ path: `.taste-skill/states/${width}-replay.jpg`, fullPage: true });
    assert.deepEqual(page.consoleErrors, []);
    results.push({ width, modal: 'pass', selectionPersistence: 'pass', escape: 'pass', previewCreation: 'pass', tabs: 'pass', hover: 'pass', consoleErrors: 0 });
    await page.close();
  }
  writeFileSync('.taste-skill/states/checks.json', JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results));
} finally { await browser.close(); }
