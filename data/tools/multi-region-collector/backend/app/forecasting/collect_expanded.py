"""Read-only, failure-isolated collection across regions and hardware candidates.

Requires boto3 only for live CLI use; core collection is dependency-injected for
offline tests. Existing collectors verify hardware, prices and pagination. No
capacity, risk labels or fitted predictions are generated by this exporter.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timedelta, timezone
import hashlib
import json
from pathlib import Path
import re

from app.forecasting.collect_spot import collect, save, stamp, utc
from app.forecasting.resource_metadata import collect_metadata, normalize_prices, save_metadata


def validate_config(config):
    if config.get("schemaVersion") != "expanded-spot-collection-config-v1":
        raise ValueError("Unsupported expanded collection configuration")
    if type(config.get("days")) is not int or not 1 <= config["days"] <= 89:
        raise ValueError("Use 1–89 days to leave collection-time margin")
    if config.get("product") != "Linux/UNIX":
        raise ValueError("This experiment requires the fixed Linux/UNIX product")
    for key in ("regions", "instanceTypes"):
        values = config.get(key)
        if not isinstance(values, list) or not values or any(
            not isinstance(v, str) or not re.fullmatch(r"[a-z0-9][a-z0-9.-]*", v) for v in values
        ) or len(values) != len(set(values)):
            raise ValueError(f"Nonempty unique safe {key} required")


def _write_receipt(output, receipt):
    # Replacement is limited to this newly created run's own receipt.
    temporary = output / "receipt.pending.json"
    temporary.write_text(json.dumps(receipt, indent=2, sort_keys=True, allow_nan=False) + "\n")
    temporary.replace(output / "receipt.json")


def _error_code(exc):
    response = getattr(exc, "response", None)
    if isinstance(response, dict):
        code = response.get("Error", {}).get("Code")
        if isinstance(code, str) and re.fullmatch(r"[A-Za-z0-9_.-]+", code):
            return code
    return type(exc).__name__


def collect_expanded(client_factory, config, output, *, end=None, retrieved_at=None):
    validate_config(config)
    if output.exists():
        raise ValueError("Output exists; use a fresh run directory")
    now = utc(retrieved_at or datetime.now(timezone.utc))
    end = utc(end) if end is not None else now.replace(minute=0, second=0, microsecond=0)
    if end.minute or end.second or end.microsecond:
        raise ValueError("End must align to a UTC hour")
    start = end - timedelta(days=config["days"])
    if not now - timedelta(days=90) <= start < end <= now:
        raise ValueError("Window must lie inside the provider's preceding 90 days")
    output.mkdir(parents=True, exist_ok=False)
    receipt = dict(schemaVersion="expanded-spot-collection-receipt-v1", config=config,
                   startTime=stamp(start), endTime=stamp(end), retrievedAt=stamp(now),
                   status="COLLECTING", pairs=[], dataKind="OBSERVED", hasCapacityObservations=False)
    _write_receipt(output, receipt)
    all_prices, all_metadata, requests = [], [], []
    for region in config["regions"]:
        for instance in config["instanceTypes"]:
            pair = dict(region=region, instanceType=instance)
            shard = output / "shards" / region / instance
            try:
                metadata, metadata_report = collect_metadata(client_factory, regions=(region,),
                    instance_types=(instance,), retrieved_at=now)
                if not metadata:
                    pair.update(status="NOT_OFFERED", priceHistoryRequested=False)
                else:
                    prices, report = collect(client_factory, start=start, end=end, regions=(region,),
                        instance_types=(instance,), product=config["product"], retrieved_at=now)
                    normalized = normalize_prices(prices, metadata)
                    save(shard / "spot-collection", prices, report)
                    metadata_report.update(inputPricesSha256=hashlib.sha256(
                        (shard / "spot-collection/prices.jsonl").read_bytes()).hexdigest(),
                        inputPriceWindow=dict(startTime=stamp(start), endTime=stamp(end), paginationComplete=True))
                    save_metadata(shard / "resource-metadata", metadata, metadata_report, normalized)
                    if prices:
                        all_prices.extend(prices)
                        all_metadata.extend(metadata)
                        requests.extend(dict(r, instanceType=instance) for r in report["requests"])
                    pair.update(status="COLLECTED" if prices else "EMPTY_PRICE_HISTORY",
                                priceHistoryRequested=True, rowCount=len(prices),
                                series=report["series"], hardware=metadata)
            except OSError:
                # Local write failures must stop the run, rather than pretending an
                # AWS pool is unavailable or continuing with an incomplete archive.
                receipt.update(status="FILESYSTEM_ERROR")
                _write_receipt(output, receipt)
                raise
            except Exception as exc:
                # Isolate provider/account failures and validation failures per pool.
                # Never write credential-bearing SDK messages or unknown payloads.
                pair.update(status="ERROR", errorCode=_error_code(exc))
            receipt["pairs"].append(pair)
            _write_receipt(output, receipt)
            print(f"{region} / {instance}: {pair['status']}", flush=True)
    included = [p for p in receipt["pairs"] if p["status"] == "COLLECTED"]
    excluded = [dict(region=p["region"], instanceType=p["instanceType"], status=p["status"],
                     **({"errorCode": p["errorCode"]} if "errorCode" in p else {}))
                for p in receipt["pairs"] if p["status"] != "COLLECTED"]
    receipt.update(status="COMPLETE" if not excluded else "PARTIAL" if included else "NO_DATA",
                   collectedPairCount=len(included), requestedPairCount=len(receipt["pairs"]),
                   excludedPairs=excluded, priceEventCount=len(all_prices))
    if all_prices:
        # These combined manifests describe complete history for the explicitly
        # included subset. Missing/failed requested pools remain in the receipt.
        scope = dict(startTime=stamp(start), endTime=stamp(end), retrievedAt=stamp(now),
                     dataKind="OBSERVED", scopeStatus=receipt["status"], excludedPairs=excluded,
                     requestedRegions=config["regions"], requestedInstanceTypes=config["instanceTypes"],
                     requests=requests, series=[s for p in included for s in p["series"]],
                     rowCount=len(all_prices), productDescription=config["product"],
                     unit="instance-hour", currency="USD", source="AWS DescribeSpotPriceHistory",
                     limitations=["Only COLLECTED pairs are included; consult receipt.json for exclusions.",
                                  "Prices do not establish available capacity or interruption risk."])
        all_prices.sort(key=lambda row: (row["region"], row["availabilityZone"], row["instanceType"], row["timestamp"]))
        save(output / "spot-collection", all_prices, scope)
        normalized = normalize_prices(all_prices, all_metadata)
        price_sha = hashlib.sha256((output / "spot-collection/prices.jsonl").read_bytes()).hexdigest()
        metadata_report = dict(schemaVersion="resource-metadata-v1", **scope,
            inputPricesSha256=price_sha,
            inputPriceWindow=dict(startTime=stamp(start), endTime=stamp(end), paginationComplete=True))
        save_metadata(output / "resource-metadata", all_metadata, metadata_report, normalized)
        receipt["combinedFilesSha256"] = {str(p.relative_to(output)): hashlib.sha256(p.read_bytes()).hexdigest()
            for folder in ("spot-collection", "resource-metadata") for p in sorted((output / folder).iterdir())}
    _write_receipt(output, receipt)
    return receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--profile")
    parser.add_argument("--end", help="Optional fixed UTC hour; default latest completed UTC hour")
    args = parser.parse_args()
    try:
        config = json.loads(args.config.read_text())
        validate_config(config)
        import boto3
        from botocore.config import Config
        session = boto3.Session(profile_name=args.profile)
        clients = {}

        def factory(region):
            if region not in clients:
                clients[region] = session.client("ec2", region_name=region,
                    config=Config(retries={"mode": "standard", "max_attempts": 4},
                                  connect_timeout=10, read_timeout=30))
            return clients[region]

        report = collect_expanded(factory, config, args.output, end=args.end)
    except ImportError:
        parser.exit(1, "Install boto3 in this environment before collection.\n")
    except (ValueError, KeyError, OSError) as exc:
        parser.exit(1, f"Collection rejected: {exc}\n")
    print(f"{report['status']}: {report['collectedPairCount']}/{report['requestedPairCount']} pairs collected.")
    print(f"Export directory: {args.output}; review receipt.json for omissions.")
    if not report["collectedPairCount"]:
        parser.exit(2, "No usable data was collected; check account permissions and regions.\n")


if __name__ == "__main__":
    main()
